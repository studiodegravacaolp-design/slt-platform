    or private.modality_name_key_v1(survivor.name) <> private.modality_name_key_v1(redundant.name)
    or redundant.created_at <> timestamptz '2026-10-05 18:34:03.343181+00'
    or redundant.updated_at <> timestamptz '2026-10-05 18:34:31.010877+00'
    or survivor.created_at <> timestamptz '2026-10-05 18:34:07.695546+00'
    or survivor.updated_at <> timestamptz '2026-10-05 18:34:07.695546+00'
  then raise exception 'Correction 02 aborted: audited 11/12 names, status, timestamps or organization/unit context changed.';
  end if;

  -- Both records were unreferenced in the approved audit. Any change requires
  -- a separate reviewed consolidation; do not silently migrate references.
  if exists (select 1 from public.student_modality_units where modality_id in (11, 12))
    or exists (select 1 from public.attendance where modality_id in (11, 12))
    or exists (select 1 from public.evaluations where modality_id in (11, 12))
    or exists (select 1 from public.trainings t join public.student_modality_units s on s.id = t.student_modality_unit_id where s.modality_id in (11, 12))
    or exists (select 1 from public.training_exercises x join public.trainings t on t.id = x.training_id join public.student_modality_units s on s.id = t.student_modality_unit_id where s.modality_id in (11, 12))
