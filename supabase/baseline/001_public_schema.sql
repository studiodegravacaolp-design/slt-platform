-- Sanitized structural baseline extracted from SLT Enterprise Clean.
-- No application rows, Auth rows, credentials or environment settings are included.
-- Apply only to a fresh Supabase project, where auth.users is platform-managed.

create schema if not exists private;

create table public.organizations (
  id bigint generated by default as identity primary key,
  name text not null, trade_name text, cnpj text, email text, phone text,
  website text, logo text, cep text, state text, city text, neighborhood text,
  street text, number text, complement text,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.units (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  name text not null, code text, email text, phone text, logo text, cep text,
  state text, city text, neighborhood text, street text, number text, complement text,
  status text not null default 'active' check (status in ('active', 'inactive')),
  is_main boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.modalities (
  id bigint generated by default as identity primary key,
  unit_id bigint not null references public.units(id) on delete restrict,
  name text not null, description text,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.students (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  full_name text not null, social_name text, birth_date date not null, cpf text, sex text,
  photo text, email text, phone text, whatsapp text, cep text, state text, city text,
  neighborhood text, street text, number text, complement text, start_date date,
  sports_notes text, status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  name text not null, email text not null, phone text, avatar text,
  status text not null default 'active' check (status in ('active', 'inactive')),
  last_access_at timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.student_modality_units (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete restrict,
  modality_id bigint not null references public.modalities(id) on delete restrict,
  unit_id bigint not null references public.units(id) on delete restrict,
  start_date date not null, end_date date,
  status text not null default 'active' check (status in ('active', 'inactive')),
  observation text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.trainings (
  id bigint generated by default as identity primary key,
  student_modality_unit_id bigint not null references public.student_modality_units(id) on delete restrict,
  name text not null, description text, objective text, observations text,
  status text not null default 'active' check (status in ('active', 'inactive')),
  start_date date, end_date date,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.training_exercises (
  id bigint generated by default as identity primary key,
  training_id bigint not null references public.trainings(id) on delete cascade,
  exercise_name text not null, sets integer check (sets is null or sets >= 0),
  repetitions integer check (repetitions is null or repetitions >= 0), load numeric,
  rest_time integer check (rest_time is null or rest_time >= 0),
  intensity text check (intensity is null or intensity in ('light', 'moderate', 'high')),
  duration integer check (duration is null or duration >= 0), observations text,
  "order" integer not null check ("order" >= 1),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique (training_id, "order")
);

create table public.attendance (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  unit_id bigint not null references public.units(id) on delete restrict,
  modality_id bigint not null references public.modalities(id) on delete restrict,
  student_id bigint not null references public.students(id) on delete restrict,
  date date not null, check_in_time time, check_out_time time,
  status text not null check (status in ('present', 'absent', 'late')), observation text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.evaluations (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  unit_id bigint not null references public.units(id) on delete restrict,
  student_id bigint not null references public.students(id) on delete restrict,
  modality_id bigint not null references public.modalities(id) on delete restrict,
  date date not null, type text not null check (type in ('performance', 'technical', 'physical', 'other')),
  responsible_user_id uuid not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.evaluation_results (
  id bigint generated by default as identity primary key,
  evaluation_id bigint not null references public.evaluations(id) on delete cascade,
  metric text not null, value text not null, unit_of_measure text, observation text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.plans (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  name text not null, description text, value numeric(12,2) not null check (value >= 0),
  periodicity text not null check (periodicity in ('monthly', 'quarterly', 'semiannual', 'annual')),
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.student_plans (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete restrict,
  plan_id bigint not null references public.plans(id) on delete restrict,
  unit_id bigint not null references public.units(id) on delete restrict,
  start_date date not null, end_date date,
  status text not null default 'active' check (status in ('active', 'closed')),
  observation text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.charges (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(id) on delete restrict,
  unit_id bigint not null references public.units(id) on delete restrict,
  student_id bigint not null references public.students(id) on delete restrict,
  student_plan_id bigint not null references public.student_plans(id) on delete restrict,
  description text, value numeric(12,2) not null check (value >= 0), issue_date date not null,
  due_date date not null,
  status text not null check (status in ('pending', 'paid', 'overdue', 'cancelled')),
  observation text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.payments (
  id bigint generated by default as identity primary key,
  charge_id bigint not null references public.charges(id) on delete restrict,
  amount_paid numeric(12,2) not null check (amount_paid > 0), payment_date date not null,
  payment_method text not null check (payment_method in ('cash', 'pix', 'card', 'transfer')),
  observation text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

