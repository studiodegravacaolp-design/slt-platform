  then raise exception 'Correction 02 aborted: modalities 11/12 now have direct or indirect references.';
  end if;

  if exists (select 1 from public.modalities where private.modality_name_key_v1(name) = '')
  then raise exception 'Correction 02 aborted: an existing modality has an empty normalized name.'; end if;

  if exists (
    select 1 from public.modalities where id <> 11
    group by unit_id, private.modality_name_key_v1(name) having count(*) > 1
  ) then raise exception 'Correction 02 aborted: other equivalent modalities require reviewed consolidation.'; end if;

  -- A newly introduced cascading reference must not turn this targeted removal
  -- into an unreviewed deletion elsewhere in the schema.
  if exists (
    select 1 from pg_catalog.pg_constraint where confrelid = 'public.modalities'::regclass
      and (confdeltype <> 'r' or conrelid not in (
        'public.student_modality_units'::regclass, 'public.attendance'::regclass, 'public.evaluations'::regclass))
  ) then raise exception 'Correction 02 aborted: unexpected foreign key references to modalities.'; end if;

  -- Retain this snapshot in the reviewed migration execution log.
  raise notice 'Correction 02 consolidating 11 -> 12; removed snapshot: %; preserved snapshot: %',
    pg_catalog.to_jsonb(redundant), pg_catalog.to_jsonb(survivor);
  delete from public.modalities where id = 11 returning id into removed_id;
  if removed_id is distinct from 11 then raise exception 'Correction 02 aborted: expected removal of only modality 11.'; end if;
end;
$preconditions$;

